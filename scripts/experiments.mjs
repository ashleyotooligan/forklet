import {mkdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {runFork,summarizeFork,forkReceipt} from '../src/lab/fork.mjs';
import {envelope} from '../src/core/engine.mjs';
import {SCENARIOS} from '../src/core/config.mjs';

export const SEEDS=[3,7,11,17,23,31,41,53,67,79,97,127];
export function runBatch(){
  return {
    schema:'forklet/batch/1',synthetic:true,
    configuration:{forkAt:24,horizon:96,duration:18,feeRate:.003},
    seeds:SEEDS,
    runs:SEEDS.flatMap(seed=>SCENARIOS.map(({id:scenario})=>summarizeFork(runFork({seed,scenario}))))
  };
}

export async function writeExperiments(){
  const root=fileURLToPath(new URL('../',import.meta.url));
  const put=async(path,value)=>writeFile(root+path,JSON.stringify(value,null,2)+'\n');
  for(const folder of ['data','examples','experiments'])await mkdir(root+folder,{recursive:true});
  const lab=runFork(),batch=runBatch();
  await put('data/default-run.json',{schema:'forklet/run/1',synthetic:true,...lab});
  await put('data/batch.json',batch);
  await put('examples/checkpoint.json',envelope(lab.checkpoint,lab.config));
  await put('examples/receipt.json',forkReceipt(lab));
  await put('examples/config.json',lab.config);
  const rows=batch.runs.filter(v=>v.seed===17).map(r=>`| ${r.scenario} | ${r.firstActionDifference??'none'} | ${r.disagreements}/${r.comparedDecisions} | ${r.meanTV.toFixed(6)} | ${r.maxHiddenL2.toFixed(6)} |`).join('\n');
  const modes=SCENARIOS.map(({id})=>{
    const runs=batch.runs.filter(r=>r.scenario===id);
    const avg=runs.reduce((s,r)=>s+r.disagreements,0)/runs.length;
    return `| ${id} | ${runs.length} | ${avg.toFixed(2)} | ${Math.min(...runs.map(r=>r.disagreements))}–${Math.max(...runs.map(r=>r.disagreements))} |`;
  }).join('\n');
  await writeFile(root+'experiments/RESULTS.md',`# Recorded results\n\nGenerated by \`npm run experiments\`. Synthetic data only. No cherry-picked market history.\n\n## Seed 17\n\nFork after decision 24; horizon 96; intervention lasts 18 decisions; 0.3% paper fee.\n\n| Intervention | First differing action | Differing actions | Mean TV distance | Maximum hidden L2 |\n|---|---:|---:|---:|---:|\n${rows}\n\n## Twelve paired seeds\n\nSeeds: ${SEEDS.join(', ')}. Each row contains the same seeds and 72 paired post-fork decisions per seed.\n\n| Intervention | Runs | Mean differing actions | Range |\n|---|---:|---:|---:|\n${modes}\n\n## Interpretation\n\nThe unchanged negative control remains identical. The late-evidence example at seed 17 changes probabilities and hidden state without changing any sampled action. A changed internal state does not guarantee a changed action. These experiments characterize this hand-specified toy controller, not financial skill, general intelligence, or real-world causal effects.\n\nFloating-point summaries may differ in the last digits between JavaScript engines. Screenshot numbers are rounded; JSON keeps full precision.\n`);
  console.log(`Generated default run, 48 paired runs, checkpoints, receipt, and results.`);
}

if(process.argv[1]===fileURLToPath(import.meta.url))await writeExperiments();
